export type MessageKey = keyof typeof messages.ru;

export function t(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  let message: string = messages[locale][key] ?? messages.ru[key];
  for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value));
  return message;
}
